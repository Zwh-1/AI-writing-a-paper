"""Export path mappings and manifest without starting the app or initializing data."""
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "backend"), str(ROOT / ".runtime/python-deps"), str(ROOT / ".runtime/advanced-deps")]


def export():
    from app.main import app
    from app.collaboration import app as collaboration_app
    registry = app.state.api_registry
    grouped = {}
    for b in registry.bindings:
        if not b.canonical:
            continue
        old = b.legacy_path.removeprefix("/api/v1")
        public = b.public_path.removeprefix("/api/v2")
        if re.sub(r"\{[^}]+\}", "{}", old) == re.sub(r"\{[^}]+\}", "{}", public):
            continue
        grouped.setdefault((old, public), []).append(b.method)
    rows = [[old, public, methods] for (old, public), methods in grouped.items()]
    source = "// Generated by scripts/export_api_contract.py. Edit backend/app/api/v2/registry.py.\n"
    source += "export const API_ROUTES: readonly (readonly [string, string, readonly string[]])[] = "
    source += json.dumps(rows, ensure_ascii=False, indent=2) + ";\n"
    (ROOT / "frontend/src/api/routes.generated.ts").write_text(source, encoding="utf-8")
    collaboration = collaboration_app.state.api_registry
    collab_rows = [[b.legacy_path.removeprefix("/collab/v1"), b.public_path.removeprefix("/api/v2"), b.method]
                   for b in collaboration.bindings if b.canonical]
    html_path = ROOT / "frontend/src/collaboration.html"
    html = html_path.read_text(encoding="utf-8")
    literal = "const COLLAB_ROUTES = " + json.dumps(collab_rows, ensure_ascii=False) + "; // generated API contract"
    html = re.sub(r"const COLLAB_ROUTES = .*?; // generated API contract", lambda _: literal, html)
    html_path.write_text(html, encoding="utf-8")
    manifest = {"workbench": registry.manifest(), "collaboration": collaboration_app.state.api_registry.manifest()}
    (ROOT / "docs/api-contract-v2.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Exported {len(rows)} frontend mappings; {sum(map(len, manifest.values()))} canonical/compatibility bindings")


if __name__ == "__main__":
    export()
