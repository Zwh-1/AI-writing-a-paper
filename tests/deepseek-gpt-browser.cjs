const fs=require('fs'),path=require('path'),assert=require('assert');
const pw=require('C:/Users/abcta/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
(async()=>{
  const root=path.resolve(__dirname,'..'),origin='http://127.0.0.1:8765';
  const session=JSON.parse(fs.readFileSync(path.join(root,'.runtime/session-8765.json'),'utf8'));
  const info=JSON.parse(fs.readFileSync(path.join(root,'.runtime/deepseek-gpt-live-probes.json'),'utf8'));
  const browser=await pw.chromium.launch({headless:true});
  const checks=[],errors=[];let generationRequests=0;
  try{
    const context=await browser.newContext({viewport:{width:1480,height:1100},locale:'zh-CN'}),page=await context.newPage();
    page.on('pageerror',e=>errors.push(e.message));
    page.on('request',r=>{if(/probe-generation|probe-image|gpt-fallback\/probe/.test(r.url()))generationRequests++;});
    await page.addInitScript(id=>localStorage.setItem('paper_project',id),info.project_id);
    await page.goto(origin+'/#token='+encodeURIComponent(session.bootstrap_token));
    await page.getByRole('button',{name:'接口与设置',exact:true}).click();
    const gpt=page.getByRole('region',{name:'GPT 备选设置'});
    await gpt.getByText('已就绪',{exact:true}).waitFor();
    assert.equal(await page.locator('input[list="model-list"]').inputValue(),'deepseek-v4.1-flash-1017');
    assert.equal(await page.getByLabel('API 中转站地址',{exact:true}).inputValue(),'https://api.x5m5x.com');
    assert.equal(await page.getByLabel('GPT API 地址',{exact:true}).inputValue(),'https://www.ecoapi.cc/v1');
    assert.equal(await page.getByLabel('GPT 模型 ID',{exact:true}).inputValue(),'gpt-6.1-sol');
    assert.equal(await page.getByLabel('GPT API key',{exact:true}).inputValue(),'');
    assert((await page.getByLabel('GPT API key',{exact:true}).getAttribute('placeholder')).includes('已保存'));
    assert(!await page.locator('select option').evaluateAll(nodes=>nodes.some(n=>/gemini/i.test(n.value+' '+n.textContent))));
    checks.push('deepseek_primary_gpt_backup_and_masked_credentials');
    await page.getByRole('button',{name:'保存 GPT 备选',exact:true}).click();
    await gpt.getByRole('status').filter({hasText:'GPT 备选已保存'}).waitFor();
    checks.push('blank_gpt_key_preserves_existing_credential');
    await page.route('**/api/v1/gpt-fallback/settings',async route=>{
      if(route.request().method()==='PUT')await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'模拟保存失败，原配置保留'})});
      else await route.continue();
    });
    await page.getByLabel('GPT API key',{exact:true}).fill('fake-ui-only-not-persisted');
    await page.getByRole('button',{name:'保存 GPT 备选',exact:true}).click();
    await gpt.getByRole('alert').filter({hasText:'模拟保存失败'}).waitFor();
    assert.equal(await page.getByLabel('GPT API key',{exact:true}).inputValue(),'fake-ui-only-not-persisted');
    await page.unroute('**/api/v1/gpt-fallback/settings');
    checks.push('save_failure_visible_and_typed_key_preserved');
    await page.reload();
    await page.getByRole('button',{name:'接口与设置',exact:true}).click();
    await gpt.getByText('已就绪',{exact:true}).waitFor();
    await page.route('**/api/v1/gpt-fallback/models',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({models:[],message:'当前密钥没有返回 GPT 模型，请在 EcoAPI 开通权限或更换密钥'})}));
    await page.getByRole('button',{name:'检测 GPT 模型',exact:true}).click();
    await gpt.getByRole('status').filter({hasText:'没有返回 GPT 模型'}).waitFor();
    await page.unroute('**/api/v1/gpt-fallback/models');
    checks.push('missing_model_permission_has_actionable_feedback');
    await page.reload();
    await page.getByRole('button',{name:'接口与设置',exact:true}).click();
    await gpt.getByText('已就绪',{exact:true}).waitFor();
    await page.screenshot({path:path.join(root,'.runtime/deepseek-gpt-settings-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await gpt.screenshot({path:path.join(root,'.runtime/deepseek-gpt-settings-mobile.png')});
    checks.push('desktop_and_mobile_settings_layout');
    assert.equal(generationRequests,0);assert.equal(errors.length,0);
    const report={passed:true,checks,page_errors:errors,generation_requests:0};
    fs.writeFileSync(path.join(root,'docs/deepseek-gpt-browser-report.json'),JSON.stringify(report,null,2));
    console.log(JSON.stringify(report));
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
