// UI completion checks use a disposable project and synthetic, free model responses.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const out=process.env.PAPER_PRODUCT_ACCEPTANCE_DIR||path.join(root,'.runtime/product-completeness-20261102');
const fixture=JSON.parse(fs.readFileSync(path.join(out,'fixture.json'),'utf8'));
const {chromium}=require(path.join(root,'.runtime/browser/node_modules/playwright'));
const checks=[],errors=[],failures=[];
async function main(){
 const candidates=fs.readdirSync(path.join(root,'.runtime/browsers')).filter(name=>name.startsWith('chromium')).flatMap(name=>['chrome-win64/chrome.exe','chrome-headless-shell-win64/chrome-headless-shell.exe'].map(tail=>path.join(root,'.runtime/browsers',name,tail)));
 const browser=await chromium.launch({headless:true,executablePath:candidates.find(name=>fs.existsSync(name))});
 const context=await browser.newContext({viewport:{width:1440,height:1050},locale:'zh-CN'});
 const page=await context.newPage();page.setDefaultTimeout(25000);
 const check=name=>{checks.push(name);console.log(name);};
 page.on('pageerror',error=>errors.push(error.message));
 page.on('response',response=>{if(response.url().includes('/api/')&&response.status()>=400)failures.push({path:new URL(response.url()).pathname,status:response.status()});});
 const clear=async()=>{const button=page.getByRole('button',{name:'清空选择',exact:true});if(await button.isEnabled())await button.click();};
 const products=async()=>{
   await page.getByRole('button',{name:'研究与协作',exact:true}).click();
   await page.getByRole('navigation',{name:'研究与协作工作区',exact:true}).getByRole('button',{name:/^产物与互通/}).click();
   await page.getByRole('heading',{name:'产物与互通',exact:true}).waitFor();
 };
 const choose=async(kind,title)=>{
   await clear();await page.getByLabel('产物类型',{exact:true}).selectOption(kind);
   const checkbox=page.getByLabel('选择产物：'+title,{exact:true});await checkbox.check();
   return page.locator('article.product-item').filter({has:checkbox});
 };
 const action=async(label)=>{
   const response=page.waitForResponse(r=>r.url().includes('/products/reuse')&&r.request().method()==='POST');
   await page.getByRole('button',{name:label,exact:true}).click();
   const result=await response;assert.equal(result.status(),200,await result.text());
   return (await result.json()).data;
 };
 try{
   const session=JSON.parse(fs.readFileSync(path.join(out,`session-${fixture.port}.json`),'utf8'));
   await page.goto(`http://127.0.0.1:${fixture.port}/#token=`+encodeURIComponent(session.bootstrap_token));
   await page.getByLabel('切换论文项目',{exact:true}).selectOption(fixture.project_id);
   await products();
   await page.getByLabel('产物类型',{exact:true}).locator('option[value="execution"]').waitFor({state:'attached'});
   assert.equal(await page.getByLabel('产物类型',{exact:true}).locator('option').count(),32);
   check('all 31 product categories are selectable in the actual workspace');
   await choose('rule','论文规则 · 复查规则要求保留全部条件。');
   await page.getByLabel('产物目标章节',{exact:true}).selectOption(fixture.empty_section_id);
   await action('补充章节计划');
   await page.getByText('已补充章节目标并关联写作材料，可在提纲与计划中查看。',{exact:true}).waitFor();
   await page.getByRole('button',{name:'提纲与写作',exact:true}).click();
   await page.locator(`[data-section-id="${fixture.empty_section_id}"]`).filter({hasText:'保留全部条件'}).waitFor();
   check('a saved rule becomes a real chapter goal in the outline feature');
   await products();
   await choose('note','复查富文本随记');
   await page.getByLabel('产物目标章节',{exact:true}).selectOption(fixture.empty_section_id);
   await action('关联本章写作材料');
   await page.getByText('已关联到本章写作材料，后续写作请求会读取实际内容与来源。',{exact:true}).waitFor();
   check('rich notes can be attached as inputs for ordinary and evidence-based writing');
   await action('生成章节草稿');
   await page.getByRole('region',{name:'互通草稿预览'}).waitFor();
   await page.getByRole('button',{name:'检查与交付',exact:true}).click();
   await products();
   await page.getByRole('region',{name:'互通草稿预览'}).waitFor();
   await page.getByLabel('产物类型',{exact:true}).selectOption('note');
   assert.equal(await page.getByLabel('选择产物：复查富文本随记',{exact:true}).isChecked(),true);
   await page.reload();await products();
   await page.getByRole('region',{name:'互通草稿预览'}).waitFor();
   check('selected products and an unadopted proposal survive navigation and a reload');
   const adoptedResponse=page.waitForResponse(r=>r.url().includes('/proposals/')&&r.url().endsWith('/adopt')&&r.request().method()==='POST');
   await page.getByRole('button',{name:'核对并采用草稿',exact:true}).click();
   const adopted=await adoptedResponse;assert.equal(adopted.status(),200,await adopted.text());
   await page.locator('.tiptap table').filter({hasText:'12'}).first().waitFor();
   await page.locator('.tiptap figure[data-artifact]').first().waitFor();
   await page.locator('.tiptap').filter({hasText:'复查富文本条件。'}).first().waitFor();
   check('an empty chapter accepts its first draft with native table, image, citation and formula');
   await page.getByRole('button',{name:'复用项目产物',exact:true}).click();
   await choose('asset','复查真实截图');
   await page.getByLabel('产物目标章节',{exact:true}).selectOption(fixture.section_id);
   await page.getByRole('button',{name:'插入图表到章节',exact:true}).click();
   await page.getByText('待插入：复查真实截图',{exact:false}).waitFor();
   await page.getByRole('button',{name:'插入到当前光标',exact:true}).click();
   const screenshotSelector=`.tiptap figure[data-artifact="${fixture.screenshot_id}"] img`;
   await page.locator(screenshotSelector).waitFor();
   await page.waitForFunction(selector=>{const image=document.querySelector(selector);return image&&image.complete&&image.naturalWidth>0;},screenshotSelector);
   check('an actual screenshot keeps its asset type and renders after editor insertion');
   await page.getByRole('button',{name:'复用项目产物',exact:true}).click();
   const noteCard=await choose('note','复查富文本随记');
   await noteCard.getByRole('button',{name:'打开原功能',exact:true}).click();
   await page.getByLabel('随记标题',{exact:true}).waitFor();
   const noteEditor=page.locator('.studio-note-editor .tiptap');
   await noteEditor.locator('[data-research-node="citation"]').waitFor();
   assert.equal(await page.getByLabel('随记标题',{exact:true}).inputValue(),'复查富文本随记');
   await noteEditor.locator('[data-research-node="formula"]').waitFor();
   await noteEditor.locator('table').waitFor();
   await noteEditor.locator('p').first().click();await noteEditor.press('End');await noteEditor.pressSequentially('补充核对记录。');
   const noteSaved=page.waitForResponse(r=>r.url().includes('/research-records/')&&r.request().method()==='PUT');
   await page.getByRole('button',{name:'保存随记',exact:true}).click();
   const noteResponse=await noteSaved;assert.equal(noteResponse.status(),200,await noteResponse.text());
   const savedNote=(await noteResponse.json()).data;
   const nodeKinds=JSON.stringify(savedNote.data.document);
   for(const type of ['citation','formula','figure','table'])assert.ok(nodeKinds.includes(`"type":"${type}"`),type);
   check('opening and editing the original note preserves all paper-specific rich nodes');
   await products();await choose('note','复查富文本随记');
   await action('存入共享资产库');
   await clear();await page.getByLabel('产物类型',{exact:true}).selectOption('asset');
   const assetCard=page.locator('article.product-item').filter({hasText:'复查富文本随记'});
   await assetCard.getByRole('button',{name:'打开原功能',exact:true}).click();
   const assetEditor=page.locator('.studio-note-editor .tiptap');
   await assetEditor.locator('table').waitFor();
   await assetEditor.locator('[data-research-node="citation"]').waitFor();
   check('a shared asset opens directly with the original editable rich structure');
   await page.getByRole('button',{name:'复用项目产物',exact:true}).click();
   const canvasCard=await choose('canvas','复查画布');
   await canvasCard.getByRole('button',{name:'打开原功能',exact:true}).click();
   await page.getByLabel('画布名称',{exact:true}).waitFor();
   await page.getByText('已保存场景，可再次编辑',{exact:true}).waitFor();
   assert.equal(await page.getByLabel('画布名称',{exact:true}).inputValue(),'复查画布');
   check('a canvas output returns to its exact editable scene');
   await page.getByRole('button',{name:'复用项目产物',exact:true}).click();
   await clear();await page.getByLabel('产物类型',{exact:true}).selectOption('parse_result');
   await page.locator('article.product-item').getByRole('button',{name:'预览',exact:true}).first().click();
   await page.locator('.product-preview pre').filter({hasText:'复查解析结果保留实际原文结构。'}).waitFor();
   check('a completed parsing result exposes its actual structured text for reuse');
   await choose('note','互通阅读随记');
   await action('加入修改检查待办');
   await page.getByRole('button',{name:'检查与交付',exact:true}).click();
   await page.locator('main').getByText('应保留样本范围和适用条件。',{exact:false}).first().waitFor();
   check('a reusable note creates an open item in the actual review workspace');
   await products();await choose('note','互通阅读随记');
   await page.getByRole('button',{name:'交给学术对话',exact:true}).click();
   await page.getByText('选择项目产物（已选 1 项）',{exact:true}).waitFor();
   await page.getByLabel('学术对话消息',{exact:true}).fill('继续分析所选材料。');
   await page.getByRole('button',{name:'发送（计费）',exact:true}).click();
   await page.getByText('已读取所选产物，并保留适用条件。',{exact:true}).waitFor();
   await page.getByRole('button',{name:'复用项目产物',exact:true}).click();
   await page.getByRole('navigation',{name:'研究与协作工作区',exact:true}).getByRole('button',{name:/^研究助手/}).click();
   await page.getByRole('tab',{name:'学术对话',exact:true}).click();
   await page.getByText('选择项目产物（已选 1 项）',{exact:true}).waitFor();
   check('a saved conversation restores its selected research products');
   await products();await page.locator('article.product-item').first().waitFor();
   await page.setViewportSize({width:430,height:932});
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2));
   await page.screenshot({path:path.join(out,'completeness-mobile.png'),fullPage:true});
   await page.setViewportSize({width:1440,height:1050});
   await page.screenshot({path:path.join(out,'completeness-desktop.png'),fullPage:true});
   check('the complete action set fits narrow and desktop layouts');
   assert.deepEqual(errors,[]);assert.deepEqual(failures,[]);
 }catch(error){
   await page.screenshot({path:path.join(out,'completeness-failure.png'),fullPage:true}).catch(()=>{});
   fs.writeFileSync(path.join(out,'completeness-failure.txt'),await page.locator('body').innerText().catch(()=>''));
   throw error;
 }finally{
   await browser.close();fs.writeFileSync(path.join(out,'completeness-browser-results.json'),JSON.stringify({checks,errors,failures},null,2));
 }
}
main().catch(error=>{console.error(error.stack);process.exitCode=1;});
