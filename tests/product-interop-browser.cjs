// Isolated UI acceptance. All AI responses are synthetic and free.
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const out = process.env.PAPER_PRODUCT_ACCEPTANCE_DIR || path.join(root, '.runtime/product-interop-20261102');
const fixture = JSON.parse(fs.readFileSync(path.join(out, 'fixture.json'), 'utf8'));
const { chromium } = require(path.join(root, '.runtime/browser/node_modules/playwright'));
const checks = [], errors = [], failures = [];
async function main() {
  const candidates = fs.readdirSync(path.join(root, '.runtime/browsers')).filter(name => name.startsWith('chromium')).flatMap(name => ['chrome-win64/chrome.exe', 'chrome-headless-shell-win64/chrome-headless-shell.exe'].map(tail => path.join(root, '.runtime/browsers', name, tail)));
  const browser = await chromium.launch({headless:true, executablePath:candidates.find(name => fs.existsSync(name))});
  const check = name => { checks.push(name); console.log(name); };
  try {
    const context = await browser.newContext({viewport:{width:1440,height:1050},locale:'zh-CN'});
    const page = await context.newPage(); page.setDefaultTimeout(20000);
    page.on('pageerror', error => errors.push(error.message));
    page.on('response', response => {if(response.url().includes('/api/') && response.status() >= 400) failures.push({path:new URL(response.url()).pathname,status:response.status()});});
    const session = JSON.parse(fs.readFileSync(path.join(out, `session-${fixture.port}.json`), 'utf8'));
    await page.goto(`http://127.0.0.1:${fixture.port}/#token=` + encodeURIComponent(session.bootstrap_token));
    await page.getByLabel('切换论文项目', {exact:true}).selectOption(fixture.project_id);
    await page.getByRole('button', {name:'研究与协作',exact:true}).click();
    await page.getByRole('navigation', {name:'研究与协作工作区'}).getByRole('button', {name:/产物与互通/}).click();
    await page.getByRole('heading', {name:'产物与互通',exact:true}).waitFor();
    await page.getByLabel('产物类型', {exact:true}).selectOption('summary');
    await page.getByLabel('选择产物：互通验收原文.txt · 总结', {exact:true}).check();
    await page.getByRole('button', {name:'预览',exact:true}).click();
    await page.locator('.product-preview pre').filter({hasText:'十二个样本'}).waitFor();
    check('catalog discovers original summary and previews real saved text');
    await page.getByRole('button', {name:'转为思维随记',exact:true}).click();
    await page.getByText('已保存到思维随记，保留所选产物的来源。', {exact:true}).waitFor();
    check('summary is reusable as a source-linked personal note');
    await page.getByLabel('产物目标章节', {exact:true}).selectOption(fixture.section_id);
    await page.getByRole('button', {name:'生成章节草稿',exact:true}).click();
    const preview = page.getByRole('region', {name:'互通草稿预览'});
    await preview.getByText('这段原有正文应完整保留。', {exact:false}).waitFor();
    await preview.getByRole('button', {name:'核对并采用草稿',exact:true}).click();
    await page.locator('.tiptap').filter({hasText:'合成实验使用十二个样本。'}).first().waitFor();
    assert.ok((await page.locator('.tiptap').first().innerText()).includes('这段原有正文应完整保留。'));
    check('reviewed summary draft reaches the editor with the existing body intact');
    await page.getByRole('button', {name:'复用项目产物',exact:true}).click();
    await page.getByRole('heading', {name:'产物与互通',exact:true}).waitFor();
    await page.getByLabel('产物目标章节', {exact:true}).locator('option[value="'+fixture.section_id+'"]').waitFor({state:'attached'});
    assert.equal(await page.getByLabel('产物目标章节', {exact:true}).inputValue(), fixture.section_id);
    check('editor passes the current section into the shared product workspace');
    if(await page.getByRole('button',{name:'清空选择',exact:true}).isEnabled())await page.getByRole('button',{name:'清空选择',exact:true}).click();
    await page.getByLabel('产物类型', {exact:true}).selectOption('note');
    await page.getByLabel('选择产物：互通阅读随记', {exact:true}).check();
    await page.getByRole('button', {name:'存入共享资产库',exact:true}).click();
    await page.getByText('已保存到共享资产库，可在研究与成果、学术对话中使用。', {exact:true}).waitFor();
    check('notes produce reusable shared text assets');
    await page.getByRole('button', {name:'交给学术对话',exact:true}).click();
    await page.getByRole('tab', {name:'学术对话',exact:true}).waitFor();
    await page.getByText('选择项目产物（已选 1 项）', {exact:true}).waitFor();
    await page.getByLabel('学术对话消息', {exact:true}).fill('请解释所选产物中的条件。');
    await page.getByRole('button', {name:'发送（计费）',exact:true}).click();
    await page.getByText('已读取所选产物，并保留适用条件。', {exact:true}).waitFor();
    const modelInput = JSON.parse(fs.readFileSync(path.join(out, 'model-input.json'), 'utf8'));
    assert.equal(modelInput.research_products[0].source_ref.id, fixture.note_id);
    check('cross-page handoff reaches the actual model input with source identity');
    await page.getByRole('button', {name:'复用项目产物',exact:true}).click();
    if(await page.getByRole('button',{name:'清空选择',exact:true}).isEnabled())await page.getByRole('button',{name:'清空选择',exact:true}).click();
    await page.getByLabel('产物类型', {exact:true}).selectOption('asset');
    await page.getByLabel('选择产物：互通流程图.png', {exact:true}).check();
    await page.getByLabel('产物目标章节', {exact:true}).selectOption(fixture.section_id);
    await page.getByRole('button', {name:'插入图表到章节',exact:true}).click();
    await page.getByText('待插入：互通流程图.png', {exact:false}).waitFor();
    await page.getByRole('button', {name:'插入到当前光标',exact:true}).click();
    await page.locator('.tiptap figure[data-artifact]').waitFor();
    check('shared image output is consumed through a durable editor insertion');
    await page.getByRole('button', {name:'复用项目产物',exact:true}).click();
    if(await page.getByRole('button',{name:'清空选择',exact:true}).isEnabled())await page.getByRole('button',{name:'清空选择',exact:true}).click();
    await page.getByLabel('产物类型', {exact:true}).selectOption('asset');
    await page.getByLabel('选择产物：互通原生三线表', {exact:true}).check();
    await page.getByLabel('产物目标章节', {exact:true}).selectOption(fixture.section_id);
    await page.getByRole('button', {name:'插入图表到章节',exact:true}).click();
    await page.getByText('待插入：互通原生三线表', {exact:false}).waitFor();
    await page.getByRole('button', {name:'插入到当前光标',exact:true}).click();
    await page.locator('.tiptap table').filter({hasText:'12'}).waitFor();
    assert.equal(await page.locator('.tiptap table td').count(),2);
    check('three-line table output remains an editable native table in the editor');
    await page.getByRole('button', {name:'复用项目产物',exact:true}).click();
    await page.getByLabel('产物类型', {exact:true}).selectOption('analysis');
    await page.getByLabel('选择产物：统计分析 · welch_t', {exact:true}).waitFor();
    await page.screenshot({path:path.join(out, 'products-desktop.png'),fullPage:true});
    check('statistics are discoverable beside writing and reading outputs');
    await page.setViewportSize({width:430,height:932});
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2));
    await page.screenshot({path:path.join(out, 'products-mobile.png'),fullPage:true});
    check('product workspace fits a 430px viewport without horizontal overflow');
    assert.deepEqual(errors, []); assert.deepEqual(failures, []);
  } finally {
    await browser.close();
    fs.writeFileSync(path.join(out, 'browser-results.json'), JSON.stringify({checks,errors,failures},null,2));
  }
}
main().catch(error => { console.error(error.stack); process.exitCode = 1; });
