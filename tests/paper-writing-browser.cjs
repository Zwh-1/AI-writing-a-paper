const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/abcta/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const root = path.resolve(__dirname, '..');
const fixture = JSON.parse(fs.readFileSync(path.join(root, '.runtime/whole-paper-browser-fixture.json'), 'utf8'));
assert.equal(fixture.synthetic_model, true, 'The browser must use an isolated synthetic project');
const origin = `http://127.0.0.1:${fixture.port}`;
const prefix = `/api/v1/projects/${fixture.project_id}`;
const output = path.join(root, '.runtime/whole-paper-browser');
fs.mkdirSync(output, { recursive: true });

(async () => {
  const session = JSON.parse(fs.readFileSync(path.join(root, `.runtime/session-${fixture.port}.json`), 'utf8'));
  const browser = await chromium.launch({ headless: true, executablePath: path.join(root, '.runtime/browsers/chromium-1234/chrome-win64/chrome.exe') });
  const errors = [], failures = [], checks = [];
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'zh-CN' });
    const authenticated = await context.request.post(origin + '/api/v1/session', { data: { token: session.bootstrap_token } });
    assert.equal(authenticated.status(), 200);
    const get = async url => { const response = await context.request.get(origin + url); assert.equal(response.status(), 200, await response.text()); return response.json(); };
    const page = await context.newPage();
    page.setDefaultTimeout(Number(process.env.PAPER_BROWSER_TIMEOUT || 45000));
    page.on('pageerror', error => errors.push(error.message));
    page.on('response', response => { if (response.url().includes('/api/') && response.status() >= 400) failures.push(response.status() + ' ' + new URL(response.url()).pathname); });
    await page.addInitScript(({ pid, sid }) => { localStorage.setItem('paper_project', pid); localStorage.setItem('paper_section', sid); }, { pid: fixture.project_id, sid: fixture.section_id });
    await page.goto(origin, { waitUntil: 'domcontentloaded' });
    const nav = page.getByRole('navigation');
    const writing = nav.getByRole('button', { name: /正文写作|写作工作台|论文写作|^写作$/ }).first();
    await writing.click();
    await page.getByRole('button', { name: '整篇论文写作', exact: true }).click();
    let dialog = page.getByRole('dialog', { name: '整篇论文写作', exact: true });
    await dialog.getByRole('heading', { name: '一次发起，完成整篇候选。', exact: true }).waitFor();
    await dialog.getByRole('button', { name: '生成整篇候选', exact: true }).waitFor();
    await dialog.getByLabel('整篇写作要求', { exact: true }).fill('完整写出本次论文草稿，保持各章研究范围一致。');
    await page.screenshot({ path: path.join(output, 'desktop-start.png') });
    for (const width of [768, 390]) {
      await page.setViewportSize({ width, height: 900 });
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Page overflow at ' + width);
      assert(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth + 1), 'Dialog overflow at ' + width);
    }
    await page.screenshot({ path: path.join(output, 'mobile-start.png') });
    await page.setViewportSize({ width: 1440, height: 1000 });
    checks.push('whole_paper_entry_and_responsive_start');
    const launched = page.waitForResponse(r => r.request().method() === 'POST' && r.url() === origin + prefix + '/paper-writing');
    await dialog.getByRole('button', { name: '生成整篇候选', exact: true }).click();
    const response = await launched;
    assert.equal(response.status(), 200, await response.text());
    let task = await response.json();
    await dialog.getByRole('heading', { name: '整篇候选已完成', exact: true }).waitFor();
    const result = await get('/api/v1/tasks/' + task.id);
    assert.equal(result.kind, 'write_paper');
    assert.equal(result.result.paper_sections.length, 5);
    assert.equal(result.result.complete, true);
    assert.equal((await get(prefix + '/sections')).filter(s => s.current_revision_id).length, 0);
    assert.equal(await dialog.locator('article[aria-label="整篇候选稿"] > section').count(), 5);
    assert(await dialog.getByRole('button', { name: '整体写入正文', exact: true }).isDisabled());
    await page.screenshot({ path: path.join(output, 'desktop-review.png') });
    checks.push('one_job_complete_candidate_includes_english_without_saving_chinese');
    await dialog.getByRole('button', { name: '关闭整篇写作', exact: true }).click();
    await page.getByRole('button', { name: '整篇论文写作', exact: true }).click();
    dialog = page.getByRole('dialog', { name: '整篇论文写作', exact: true });
    await dialog.getByRole('heading', { name: '整篇候选已完成', exact: true }).waitFor();
    checks.push('closing_and_reopening_retains_whole_candidate');
    const originalTask = task;
    const originalIntroduction = result.result.paper_sections.find(s => s.kind === 'introduction');
    const findings = dialog.getByLabel('全文审阅问题', { exact: true });
    const implementationFinding = findings.locator('.paper-finding').filter({ hasText: '第二章 实现' }).first();
    const findingDetails = findings.locator('details').first();
    if (await findingDetails.getAttribute('open') === null)
      await findings.getByText('查看并选择需要修订的问题', { exact: true }).click();
    await implementationFinding.getByRole('checkbox').check();
    await implementationFinding.getByRole('button', { name: '定位章节', exact: true }).click();
    await dialog.getByLabel('整篇修订要求', { exact: true }).fill('补充实现章的关键流程解释，保留其他章，统一修订结论和摘要。');
    const revisedRequest = page.waitForResponse(r => r.request().method() === 'POST' && r.url() === origin + prefix + `/paper-writing/${task.id}/revise`);
    await dialog.getByRole('button', { name: '修订并重新审阅整篇', exact: true }).click();
    const revisedResponse = await revisedRequest;
    assert.equal(revisedResponse.status(), 200, await revisedResponse.text());
    task = await revisedResponse.json();
    await dialog.getByText(/第 1 轮整篇修订/).waitFor();
    await dialog.getByRole('heading', { name: '整篇候选已完成', exact: true }).waitFor();
    const revised = await get('/api/v1/tasks/' + task.id);
    assert.equal(revised.result.retained_sections, 1);
    assert.equal(revised.result.revised_sections, 4);
    assert.deepEqual(revised.result.paper_sections.find(s => s.kind === 'introduction').document, originalIntroduction.document);
    assert.equal((await get('/api/v1/tasks/' + originalTask.id)).result.superseded_by_task_id, task.id);
    assert.equal((await get(prefix + '/sections')).filter(s => s.current_revision_id).length, 0);
    assert(await dialog.getByRole('button', { name: '整体写入正文', exact: true }).isDisabled());
    await page.screenshot({ path: path.join(output, 'desktop-revised.png') });
    checks.push('selected_review_issue_revises_affected_chapters_and_preserves_complete_candidate');
    await page.setViewportSize({ width: 390, height: 900 });
    assert(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth + 1));
    await page.screenshot({ path: path.join(output, 'mobile-review.png') });
    await dialog.getByRole('checkbox', { name: '我已统一审阅整篇候选，同意将全部章节写入为草稿', exact: true }).check();
    const accepted = page.waitForResponse(r => r.request().method() === 'POST' && r.url() === origin + prefix + `/paper-writing/${task.id}/accept`);
    await dialog.getByRole('button', { name: '整体写入正文', exact: true }).click();
    const receipt = await accepted;
    assert.equal(receipt.status(), 200, await receipt.text());
    await dialog.getByRole('heading', { name: '整篇已写入正文', exact: true }).waitFor();
    const sections = await get(prefix + '/sections');
    assert.equal(sections.filter(s => s.current_revision_id).length, 5);
    assert(sections.every(s => s.state === 'draft'));
    await page.screenshot({ path: path.join(output, 'mobile-adopted.png') });
    checks.push('single_review_action_adopts_all_chapters_as_drafts');
    await page.setViewportSize({ width: 1440, height: 1000 });
    await dialog.getByRole('button', { name: '新建整篇任务', exact: true }).click();
    await dialog.getByLabel('整篇写作要求', { exact: true }).fill('预算中断样例：完成后继续写作。');
    const pauseRequest = page.waitForResponse(r => r.request().method() === 'POST' && r.url() === origin + prefix + '/paper-writing');
    await dialog.getByRole('button', { name: '生成整篇候选', exact: true }).click();
    const pausedTask = await (await pauseRequest).json();
    await dialog.getByRole('heading', { name: '整篇进度已保留', exact: true }).waitFor();
    const paused = await get('/api/v1/tasks/' + pausedTask.id);
    assert.equal(paused.status, 'budget_blocked');
    assert.equal(paused.result.paper_sections.length, 1);
    assert.equal(paused.resume_requires_ack, false);
    assert.equal(await dialog.getByRole('checkbox', { name: /可能再次计费/ }).count(), 0);
    const firstCandidate = JSON.stringify(paused.result.paper_sections[0]);
    const continued = page.waitForResponse(r => r.request().method() === 'POST' && r.url() === origin + prefix + `/paper-writing/${pausedTask.id}/resume`);
    await dialog.getByRole('button', { name: '继续完成整篇', exact: true }).click();
    assert.equal((await continued).status(), 200);
    await dialog.getByRole('heading', { name: '整篇候选已完成', exact: true }).waitFor();
    const resumed = await get('/api/v1/tasks/' + pausedTask.id);
    assert.equal(resumed.result.paper_sections.length, 5);
    assert(resumed.result.paper_sections.some(item => JSON.stringify(item) === firstCandidate));
    checks.push('budget_pause_can_resume_without_regenerating_completed_content');
    assert.deepEqual(errors, []);
    assert.deepEqual(failures, []);
    fs.writeFileSync(path.join(output, 'report.json'), JSON.stringify({ checks, errors, failures, task_id: task.id, sections: sections.length, synthetic_model: true }, null, 2));
    process.stdout.write(JSON.stringify({ checks, errors, failures }, null, 2) + '\n');
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
